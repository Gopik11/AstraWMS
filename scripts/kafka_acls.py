#!/usr/bin/env python3
"""Kafka ACLs per service account, derived from the source (ADR-0029, review H-02).

Each service's SASL account (deploy/vps: one per service, ADR-0018) gets only what its code needs:
  - WRITE on the topics it publishes through the outbox (OutboxWriter.Message);
  - READ on the topics its @KafkaListener methods consume, and READ on its consumer groups (prefix = the service
    name, plus the SAP adapter's `webhooks.` groups); the DLQ browser group is `<service>-dlq-browser`;
  - WRITE on `<topic>.dlq` of every consumed topic (dead-lettering) and READ on it (the Operations page), and WRITE on
    the consumed topic itself (a replay goes back to the original topic);
  - DESCRIBE and CREATE on every topic it declares (it creates missing topics at start-up) and ALTER (it may add
    partitions to match its declaration).
Writes deploy/kafka/acls.txt, applied by deploy/vps/kafka-acls.sh.

  python3 scripts/kafka_acls.py          # regenerate
  python3 scripts/kafka_acls.py --check  # fail when the committed ACLs are stale (CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "kafka" / "acls.txt"
SERVICES = {"master-data-service": "services/master-data-service", "inventory-service": "services/inventory-service",
            "inbound-service": "services/inbound-service", "task-service": "services/task-service",
            "outbound-service": "services/outbound-service", "sap-adapter": "adapters/sap-adapter"}
# accessor methods of configurable topic names and their defaults (inventory's InventoryEvents.Topics)
ACCESSORS = {"topics.inventoryEvents()": "InventoryContracts.TOPIC",
             "topics.goodsMovements()": "IntegrationContracts.TOPIC_GOODS_MOVEMENTS",
             "topics.masterdataEvents()": "MasterDataEvents.TOPIC"}


def constants():
    out = {}
    for p in (ROOT / "platform/astra-common/src/main/java/com/astrawms/common/contracts").glob("*.java"):
        for m in re.finditer(r'String (TOPIC[A-Z_]*) = "([^"]+)"', p.read_text(encoding="utf-8")):
            out[f"{p.stem}.{m.group(1)}"] = m.group(2)
    return out


def resolve(expr, consts):
    expr = expr.strip().strip('"')
    expr = ACCESSORS.get(expr, expr)
    m = re.fullmatch(r"\$\{[^:}]+:([^}]+)\}", expr)
    if m:
        return m.group(1)
    short = expr.replace("com.astrawms.common.contracts.", "")
    if short in consts:
        return consts[short]
    if re.fullmatch(r"[a-z0-9.]+", expr):
        return expr
    raise SystemExit(f"kafka_acls.py: cannot resolve topic expression {expr!r}; add it to ACCESSORS")


def scan(consts):
    spec = {}
    for svc, path in SERVICES.items():
        produce, consume, groups, declared = set(), set(), set(), set()
        for p in (ROOT / path).glob("src/main/java/**/*.java"):
            s = p.read_text(encoding="utf-8")
            for m in re.finditer(r"OutboxWriter\.Message\(\s*([\w.()]+)", s):
                produce.add(resolve(m.group(1), consts))
            for m in re.finditer(r'@KafkaListener\(\s*topics\s*=\s*("[^"]+"|[\w.]+)[^)]*?groupId\s*=\s*"([^"]+)"', s, re.S):
                consume.add(resolve(m.group(1), consts))
                groups.add(m.group(2))
            for m in re.finditer(r"TopicBuilder\.name\(\s*([\w.]+(?:\(\))?)\s*\)", s):
                declared.add(resolve(m.group(1), consts))
        prefixes = {svc}
        prefixes.update(g.split(".")[0] + "." for g in groups if not g.startswith(svc))
        spec[svc] = {"produce": produce, "consume": consume, "groupPrefixes": prefixes, "declared": declared}
    return spec


def render(spec):
    lines = ["# Kafka ACLs per service account. Generated by scripts/kafka_acls.py (ADR-0029); applied by",
             "# deploy/vps/kafka-acls.sh. Do not edit: change the code and regenerate.",
             "# principal operation resource-type pattern-type name"]
    for svc, s in spec.items():
        rows = set()
        for t in s["produce"]:
            rows.add(("WRITE", "TOPIC", "LITERAL", t))
        for t in s["consume"]:
            rows |= {("READ", "TOPIC", "LITERAL", t), ("WRITE", "TOPIC", "LITERAL", t),
                     ("READ", "TOPIC", "LITERAL", t + ".dlq"), ("WRITE", "TOPIC", "LITERAL", t + ".dlq"),
                     ("CREATE", "TOPIC", "LITERAL", t + ".dlq"), ("DESCRIBE", "TOPIC", "LITERAL", t + ".dlq")}
        for t in s["produce"] | s["consume"] | s["declared"]:
            rows |= {("DESCRIBE", "TOPIC", "LITERAL", t), ("CREATE", "TOPIC", "LITERAL", t),
                     ("ALTER", "TOPIC", "LITERAL", t)}
        for g in s["groupPrefixes"]:
            rows.add(("READ", "GROUP", "PREFIXED", g))
        for op, rtype, ptype, name in sorted(rows, key=lambda r: (r[1], r[3], r[0])):
            lines.append(f"User:{svc} {op} {rtype} {ptype} {name}")
    return "\n".join(lines) + "\n"


def main():
    text = render(scan(constants()))
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("deploy/kafka/acls.txt is stale: run python3 scripts/kafka_acls.py", file=sys.stderr)
            sys.exit(1)
        print("Kafka ACLs: up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
